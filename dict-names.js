// Названия «системных» значений справочников по ключам: тип работ 1/2/3 и инициатор 1/2.
// Страницы сравнивают данные с этими названиями, поэтому после переименования значения
// в справочнике («Словарь разбора» → «Справочники») берут новое название из базы, а не из кода.
// По умолчанию — текущие названия (если запрос не прошёл, страница работает как раньше).
export const DN = { em: "Аварийные работы", pl: "Плановые работы", to: "Тех. Обслуживание", mine: "Рудник", service: "Сервис" };

export async function loadDictNames(supabase) {
  try {
    const { data } = await supabase.rpc("dict_system_names");
    if (data) for (const k of Object.keys(DN)) if (data[k]) DN[k] = data[k];
  } catch (_) {}
  return DN;
}
